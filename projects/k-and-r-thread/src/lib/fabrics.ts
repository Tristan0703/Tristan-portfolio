export const getFabricById = (id: string): FabricData | undefined => {
  return fabrics.find((f) => f.id === id);
};

export const getVaultFabrics = (): FabricData[] => {
  return fabrics.filter((f) => f.isVault);
};

export const getFabricsByWeight = (minGsm: number, maxGsm: number): FabricData[] => {
  return fabrics.filter((f) => f.gsm >= minGsm && f.gsm <= maxGsm);
};

